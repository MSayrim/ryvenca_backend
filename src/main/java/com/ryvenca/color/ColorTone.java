package com.ryvenca.color;

/** How a color behaves when combining outfits. */
public enum ColorTone {
    /** Goes with almost everything: black, white, gray, cream, beige, brown, navy. */
    NEUTRAL,
    /** Deep, muted colors that behave almost like neutrals: olive, burgundy. */
    EARTH,
    /** Light, low-saturation colors: light blue, pink. */
    SOFT,
    /** Saturated statement colors. */
    ACCENT
}
